def iso(d):
    return d.isoformat()


def build():
    docs = {"settings": {}, "weeks": {}, "tasks": {}, "questions": {}}
    docs["settings"]["main"] = {
        "start": iso(START),
        "deadline": "2027-02-28",
        "minimum": {"algoMin": 30, "trainer": 10, "apps": 1},
        "createdAt": "2026-10-19",
    }
    for n, (phase, theme, lc_topic, hours, lc, apps, net, mock, light, milestone) in WEEKS.items():
        start = START + timedelta(days=7 * (n - 1))
        wid = f"W{n:02d}"
        doc = {
            "n": n,
            "start": iso(start),
            "end": iso(start + timedelta(days=6)),
            "phase": phase,
            "phaseName": PHASES[phase],
            "theme": theme,
            "lcTopic": lc_topic,
            "light": light,
            "targets": {"hours": hours, "lc": lc, "apps": apps, "net": net, "mock": mock},
        }
        if milestone:
            doc["milestone"] = milestone
        docs["weeks"][wid] = doc
        for i, (track, title) in enumerate(TASKS[n]):
            tid = f"w{n:02d}-{i + 1:02d}"
            docs["tasks"][tid] = {"week": n, "track": track, "title": title, "done": False, "order": i + 1}
    for i, (topic, q, keys) in enumerate(QUESTIONS):
        qid = f"q{i + 1:03d}"
        docs["questions"][qid] = {
            "topic": topic,
            "q": q,
            "keys": [k.strip() for k in keys.split("|")],
            "box": 0,
            "due": None,
            "reviews": 0,
        }
    return docs


def main():
    docs = build()
    for coll, items in docs.items():
        os.makedirs(os.path.join(OUT, coll), exist_ok=True)
        for doc_id, body in items.items():
            with open(os.path.join(OUT, coll, f"{doc_id}.json"), "w", encoding="utf-8") as f:
                json.dump(body, f, ensure_ascii=False)
    with open(os.path.join(OUT, "all.json"), "w", encoding="utf-8") as f:
        json.dump(docs, f, ensure_ascii=False)
    print({k: len(v) for k, v in docs.items()})


if __name__ == "__main__":
    main()
